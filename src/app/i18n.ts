/**
 * Minimal DE/EN switch for the statistics (dashboard and video overlays).
 * German text is the key; t() returns the English text when English is selected.
 */
import { reactive, watch } from 'vue';

export type Lang = 'de' | 'en';

const STORE_KEY = 'lang';
function load(): Lang {
  try {
    return localStorage.getItem(STORE_KEY) === 'en' ? 'en' : 'de';
  } catch {
    return 'de';
  }
}

export const i18n = reactive({ lang: load() });
watch(() => i18n.lang, (l) => {
  // screen readers and hyphenation follow the page language
  document.documentElement.lang = l;
  try {
    localStorage.setItem(STORE_KEY, l);
  } catch {
    /* private mode */
  }
}, { immediate: true });

/** Locale for number and date formatting */
export const locale = () => (i18n.lang === 'en' ? 'en-GB' : 'de-CH');

export function t(de: string): string {
  return i18n.lang === 'en' ? (EN[de] ?? de) : de;
}

